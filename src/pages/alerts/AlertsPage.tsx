import { useCallback, useEffect, useState } from 'react'
import { Link, useSearchParams } from 'react-router-dom'
import {
  Alert,
  Box,
  Button,
  Card,
  CardContent,
  Chip,
  Stack,
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableRow,
  Typography,
} from '@mui/material'
import ApiFeedback from '../../components/common/ApiFeedback'
import { useApiData } from '../../hooks/useApiData'
import {
  acknowledgeAlert,
  acknowledgeGeofenceAlert,
  getGeofenceAlerts,
  listAlerts,
  resolveAlert,
  resolveGeofenceAlert,
} from '../../services/api'

function formatDate(val?: string) {
  if (!val) return '—'
  const d = new Date(val)
  return Number.isNaN(d.getTime()) ? val : d.toLocaleString()
}

function AlertsPage() {
  const [searchParams] = useSearchParams()
  const geofenceOnly = searchParams.get('type') === 'geofence'
  const [actionError, setActionError] = useState('')
  const loadAlerts = useCallback(
    () => geofenceOnly ? getGeofenceAlerts({ skip: 0, limit: 500 }) : listAlerts(0, 500),
    [geofenceOnly],
  )
  const { data: alerts, loading, error, reload } = useApiData(loadAlerts)

  useEffect(() => {
    if (!geofenceOnly) return
    const refresh = () => reload()
    window.addEventListener('trackguard:geofence-live-alert', refresh)
    window.addEventListener('trackguard:geofence-alert-refresh', refresh)
    window.addEventListener('trackguard:alert-socket', refresh)
    return () => {
      window.removeEventListener('trackguard:geofence-live-alert', refresh)
      window.removeEventListener('trackguard:geofence-alert-refresh', refresh)
      window.removeEventListener('trackguard:alert-socket', refresh)
    }
  }, [geofenceOnly, reload])

  const runAction = async (id: number | string, action: 'acknowledge' | 'resolve') => {
    setActionError('')
    try {
      if (geofenceOnly) {
        if (action === 'acknowledge') await acknowledgeGeofenceAlert(id)
        else await resolveGeofenceAlert(id)
      } else if (action === 'acknowledge') await acknowledgeAlert(id)
      else await resolveAlert(id)
      reload()
      window.dispatchEvent(new Event('trackguard:geofence-alert-refresh'))
    } catch (reason) {
      let errorMsg = 'Unable to update alert.'
      if (reason instanceof Error) {
        try {
          const parsed = JSON.parse(reason.message)
          if (Array.isArray(parsed) && parsed[0]?.msg) {
            errorMsg = parsed[0].msg
          } else if (parsed?.detail) {
            errorMsg = typeof parsed.detail === 'string' ? parsed.detail : JSON.stringify(parsed.detail)
          } else {
            errorMsg = reason.message
          }
        } catch {
          errorMsg = reason.message
        }
      }
      setActionError(errorMsg)
    }
  }

  return (
    <Stack spacing={3}>
      <Box>
        <Typography variant="h4" sx={{ fontWeight: 700, color: '#071a2e' }}>
          {geofenceOnly ? 'Geofence Alert History' : 'Alerts'}
        </Typography>
        <Typography variant="body2" color="text.secondary">
          {geofenceOnly ? 'Entry and exit alerts generated by configured geofences' : 'Monitoring and security incident management'}
        </Typography>
        {geofenceOnly && (
          <Button component={Link} to="/admin/alerts" sx={{ mt: 1, textTransform: 'none' }}>
            View all alerts
          </Button>
        )}
      </Box>

      {actionError && <Alert severity="error" onClose={() => setActionError('')}>{actionError}</Alert>}

      <Card sx={{ borderRadius: 3, boxShadow: '0 1px 4px rgba(0,0,0,0.05)', border: '1px solid #e2e8f0' }}>
        <CardContent sx={{ p: 0 }}>
          <Table>
            <TableHead sx={{ bgcolor: '#f8fafc' }}>
              <TableRow>
                <TableCell sx={{ fontWeight: 700, fontSize: 12, textTransform: 'uppercase', color: '#64748b' }}>Time</TableCell>
                <TableCell sx={{ fontWeight: 700, fontSize: 12, textTransform: 'uppercase', color: '#64748b' }}>Device</TableCell>
                <TableCell sx={{ fontWeight: 700, fontSize: 12, textTransform: 'uppercase', color: '#64748b' }}>Alert Type</TableCell>
                <TableCell sx={{ fontWeight: 700, fontSize: 12, textTransform: 'uppercase', color: '#64748b' }}>Message</TableCell>
                <TableCell sx={{ fontWeight: 700, fontSize: 12, textTransform: 'uppercase', color: '#64748b' }}>Location</TableCell>
                <TableCell sx={{ fontWeight: 700, fontSize: 12, textTransform: 'uppercase', color: '#64748b' }}>Severity</TableCell>
                <TableCell sx={{ fontWeight: 700, fontSize: 12, textTransform: 'uppercase', color: '#64748b' }}>Status</TableCell>
                <TableCell sx={{ fontWeight: 700, fontSize: 12, textTransform: 'uppercase', color: '#64748b' }}>Actions</TableCell>
              </TableRow>
            </TableHead>
            <TableBody>
              {alerts?.map((alert) => {
                const sev = (alert?.severity || 'high').toLowerCase()
                const status = (alert?.status || 'NEW').toLowerCase()
                const typeText = alert?.type || alert?.alert_type || 'ALARM'
                const msgText = alert?.message || typeText
                const mapParams = new URLSearchParams()
                const deviceId = alert.device_id ?? alert.imei
                if (deviceId != null) mapParams.set('device', String(deviceId))
                if (alert.geofence_id != null) mapParams.set('geofence', String(alert.geofence_id))
                const mapHref = `/admin/geofences${mapParams.size ? `?${mapParams.toString()}` : ''}`

                return (
                  <TableRow key={alert.id} hover>
                    <TableCell sx={{ fontSize: 13, color: '#64748b' }}>
                      {formatDate(alert.event_time || alert.created_at || alert.received_at || '')}
                    </TableCell>
                    <TableCell sx={{ fontWeight: 600, fontSize: 13 }}>
                      {alert.device_name || alert.device_id || alert.imei || 'Band'}
                      {geofenceOnly && alert.geofence_name && (
                        <Typography variant="caption" sx={{ display: 'block' }} color="text.secondary">
                          {alert.geofence_name}
                        </Typography>
                      )}
                    </TableCell>
                    <TableCell>
                      <Chip label={typeText} size="small" sx={{ fontWeight: 600, fontSize: 11 }} />
                    </TableCell>
                    <TableCell sx={{ fontSize: 13, color: '#334155' }}>
                      {msgText}
                    </TableCell>
                    <TableCell sx={{ fontSize: 12, fontFamily: 'monospace' }}>
                      {alert.latitude != null && alert.longitude != null && Number.isFinite(alert.latitude) && Number.isFinite(alert.longitude) ? (
                        <Box>
                          <Typography variant="body2" sx={{ fontFamily: 'monospace', fontSize: 12, color: '#334155' }}>
                            {alert.latitude.toFixed(4)}, {alert.longitude.toFixed(4)}
                          </Typography>
                          {alert.location_is_stale || alert.location_source === 'HISTORICAL' ? (
                            <Typography variant="caption" sx={{ color: '#d97706', fontSize: 10, display: 'block' }}>
                              Historical snapshot
                            </Typography>
                          ) : (
                            <Typography variant="caption" sx={{ color: '#059669', fontSize: 10, display: 'block' }}>
                              Live GPS fix
                            </Typography>
                          )}
                        </Box>
                      ) : (
                        <Typography variant="caption" sx={{ color: '#94a3b8', fontStyle: 'italic' }}>
                          Location Unavailable
                        </Typography>
                      )}
                    </TableCell>
                    <TableCell>
                      <Chip
                        label={alert?.severity || sev}
                        size="small"
                        color={sev === 'critical' ? 'error' : sev === 'high' ? 'warning' : sev === 'medium' ? 'secondary' : 'default'}
                        sx={{ fontWeight: 600, textTransform: 'uppercase', fontSize: 10 }}
                      />
                    </TableCell>
                    <TableCell sx={{ fontSize: 12, fontWeight: 600, textTransform: 'uppercase' }}>
                      {alert?.status || 'NEW'}
                      {alert.acknowledged_by != null && (
                        <Typography variant="caption" sx={{ display: 'block', fontWeight: 400, textTransform: 'none' }}>
                          Acknowledged by {alert.acknowledged_by}
                          {alert.acknowledged_at ? ` · ${formatDate(alert.acknowledged_at)}` : ''}
                        </Typography>
                      )}
                    </TableCell>
                    <TableCell>
                      <Stack direction="row" spacing={1}>
                        {geofenceOnly && (
                          <Button size="small" component={Link} to={mapHref}>
                            View on Map
                          </Button>
                        )}
                        {status !== 'acknowledged' && status !== 'resolved' && (
                          <Button size="small" variant="outlined" onClick={() => void runAction(alert.alert_id ?? alert.id, 'acknowledge')}>
                            Acknowledge
                          </Button>
                        )}
                        {status !== 'resolved' && (
                          <Button size="small" color="success" variant="contained" onClick={() => void runAction(alert.alert_id ?? alert.id, 'resolve')}>
                            Resolve
                          </Button>
                        )}
                      </Stack>
                    </TableCell>
                  </TableRow>
                )
              })}

              {alerts && alerts.length === 0 && (
                <TableRow>
                  <TableCell colSpan={8}>
                    <ApiFeedback loading={false} error="" empty emptyMessage="No active alerts recorded by the API." />
                  </TableCell>
                </TableRow>
              )}
            </TableBody>
          </Table>

          {!alerts && <ApiFeedback loading={loading} error={error} empty={false} emptyMessage="" />}
        </CardContent>
      </Card>
    </Stack>
  )
}

export default AlertsPage
